# Different data types in Python

name = "Kruti"           # String (str)
age = 21                 # Integer (int)
percentage = 85.5         # Float (float)
is_student = True         # Boolean (bool)
subjects = ["Python", "R", "SQL"]  # List
numbers = (10, 20, 30)    # Tuple
student = {"name": "Kruti", "age": 21}  # Dictionary
unique_numbers = {1, 2, 3}  # Set

print(name, type(name))
print(age, type(age))
print(percentage, type(percentage))
print(is_student, type(is_student))
print(subjects, type(subjects))
print(numbers, type(numbers))
print(student, type(student))
print(unique_numbers, type(unique_numbers))

'''
Kruti <class 'str'>
21 <class 'int'>
85.5 <class 'float'>
True <class 'bool'>
['Python', 'R', 'SQL'] <class 'list'>
(10, 20, 30) <class 'tuple'>
{'name': 'Kruti', 'age': 21} <class 'dict'>
{1, 2, 3} <class 'set'>
'''
